"""Build data/greenbook_texas_1956.csv and data/ocr_corrections.md.

Inputs
  data/greenbook_texas_1956_transcription.tsv  entries transcribed by hand from the
      Fall 1956 page images (NYPL image ids 5206271 to 5206274).
  <ocr_dir>/<page_image_id>g.txt  NYPL per-page OCR text, used only as a cross-check.

Each transcribed entry is aligned, in order, to the OCR line that best matches it.
Any difference between the OCR and the transcription is recorded, never silently fixed.

Usage: python3 scripts/build_greenbook_csv.py /tmp/nypl-greenbooks/1956
"""
import csv
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TRANSCRIPTION = ROOT / "data" / "greenbook_texas_1956_transcription.tsv"
OUT_CSV = ROOT / "data" / "greenbook_texas_1956.csv"
OUT_LOG = ROOT / "data" / "ocr_corrections.md"

MATCH_THRESHOLD = 0.55
LEADER = re.compile(r"\s*(?:\.\s*){3,}\s*")
FIELDS = [
    "id", "name", "category", "address_raw", "city",
    "source_page_image_id", "ocr_confidence_note",
]


def split_ocr_line(line):
    """Split an OCR line into (name, address) on the dot leader."""
    parts = LEADER.split(line.strip(), maxsplit=1)
    name = parts[0].strip()
    address = parts[1].strip() if len(parts) > 1 else ""
    return name, address


def norm(text):
    return re.sub(r"[^a-z0-9]", "", text.lower())


def load_ocr_lines(ocr_dir, page_id):
    path = Path(ocr_dir) / f"{page_id}g.txt"
    return [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]


def find_ocr_match(name, ocr_lines, start):
    """Return (index, ocr_name, ocr_address, ratio) of the best line at or after start."""
    best = (None, "", "", 0.0)
    for idx in range(start, len(ocr_lines)):
        ocr_name, ocr_addr = split_ocr_line(ocr_lines[idx])
        ratio = difflib.SequenceMatcher(None, norm(name), norm(ocr_name)).ratio()
        if ratio > best[3]:
            best = (idx, ocr_name, ocr_addr, ratio)
        if ratio >= 0.95:
            break
    return best


def describe_difference(entry, ocr_name, ocr_addr, ratio):
    """Return a short note on how the OCR differs from the transcription, or ''."""
    if ratio < MATCH_THRESHOLD:
        return "OCR line too garbled to match; transcribed from page image"
    notes = []
    if norm(ocr_name) != norm(entry["name"]):
        notes.append(f'OCR name read "{ocr_name}"')
    if entry["address"] and norm(ocr_addr) != norm(entry["address"]):
        notes.append(f'OCR address read "{ocr_addr}"')
    return "; ".join(notes)


def build_rows(ocr_dir):
    with TRANSCRIPTION.open(encoding="utf-8", newline="") as fh:
        entries = list(csv.DictReader(fh, delimiter="\t"))

    pages = {}
    rows, log = [], []
    cursor = {}
    for number, entry in enumerate(entries, start=1):
        page = entry["page_image_id"]
        pages.setdefault(page, load_ocr_lines(ocr_dir, page))
        idx, ocr_name, ocr_addr, ratio = find_ocr_match(
            entry["name"], pages[page], cursor.get(page, 0)
        )
        matched = idx is not None and ratio >= MATCH_THRESHOLD
        if matched:
            cursor[page] = idx + 1
        diff = describe_difference(entry, ocr_name, ocr_addr, ratio)
        notes = [n for n in (entry["transcription_note"], diff) if n]
        note = "; ".join(notes) if notes else "OCR agrees with page image"
        row_id = f"gb1956-tx-{number:03d}"
        rows.append({
            "id": row_id,
            "name": entry["name"],
            "category": entry["category"],
            "address_raw": entry["address"],
            "city": entry["city"],
            "source_page_image_id": page,
            "ocr_confidence_note": note,
        })
        if notes:
            log.append((row_id, page, entry["city"], entry["name"], note))
    return rows, log


def write_csv(rows):
    with OUT_CSV.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)


def write_log(rows, log):
    clean = len(rows) - len(log)
    lines = [
        "# OCR corrections log (Texas, Fall 1956)",
        "",
        "Generated by `scripts/build_greenbook_csv.py`. Every entry was transcribed by hand",
        "from the page images (NYPL image ids 5206271 to 5206274, printed pages 60 to 63)",
        "and compared with the NYPL OCR text. Names and addresses were not changed when",
        "unsure; the entries below are the ones where the OCR and the page image differ,",
        "or where the printed page itself has a gap or typo.",
        "",
        f"- Entries transcribed: {len(rows)}",
        f"- Entries where the OCR agreed with the page image: {clean}",
        f"- Entries with a difference or note: {len(log)}",
        "",
        "| id | page image | city | entry | what differed |",
        "|----|------------|------|-------|---------------|",
    ]
    for row_id, page, city, name, note in log:
        safe_note = note.replace("|", "/")
        lines.append(f"| {row_id} | {page} | {city} | {name} | {safe_note} |")
    OUT_LOG.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rows, log = build_rows(sys.argv[1])
    write_csv(rows)
    write_log(rows, log)
    cities = {r["city"] for r in rows}
    print(f"{len(rows)} entries, {len(cities)} towns, {len(log)} with notes")


if __name__ == "__main__":
    main()
